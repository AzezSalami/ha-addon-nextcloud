#!/usr/bin/env bash
# Web server (Apache) port/TLS setup helpers. Source, do not execute.
#
# Container port 80 always serves plain HTTP (for a tunnel or reverse proxy on the internal network).
# Container port 443 is the "web interface" port published by Home Assistant: HTTPS when ssl=true,
# plain HTTP otherwise, so the "Open Web UI" button can use [PROTO:ssl] with one fixed port.

NC_SSL_DIR="${NC_SSL_DIR:-/ssl}"
NC_APACHE_UI_CONF="${NC_APACHE_UI_CONF:-/etc/apache2/conf-enabled/addon-ui.conf}"

# ssl_check_pair <cert> <key> [allow_expired]: prints "SSL ERROR: ..." / "SSL WARNING: ..." lines; returns non-zero on any error.
# With allow_expired=true an expired certificate is only a warning (everything else stays an error).
ssl_check_pair() {
    local cert="$1" key="$2" allow_expired="${3:-false}" rc=0 pub_c pub_k
    [ -r "$cert" ] || { echo "SSL ERROR: certificate file not found or not readable: $cert (put it in Home Assistant's /ssl folder)"; rc=1; }
    [ -r "$key" ] || { echo "SSL ERROR: key file not found or not readable: $key (put it in Home Assistant's /ssl folder)"; rc=1; }
    [ "$rc" = 0 ] || return 1

    openssl x509 -in "$cert" -noout >/dev/null 2>&1 || { echo "SSL ERROR: $cert is not a valid PEM certificate"; return 1; }
    openssl pkey -in "$key" -noout -passin pass: >/dev/null 2>&1 || { echo "SSL ERROR: $key is not a valid unencrypted PEM private key"; return 1; }

    pub_c="$(openssl x509 -in "$cert" -noout -pubkey 2>/dev/null | openssl pkey -pubin -outform DER 2>/dev/null | sha256sum)"
    pub_k="$(openssl pkey -in "$key" -passin pass: -pubout -outform DER 2>/dev/null | sha256sum)"
    [ "$pub_c" = "$pub_k" ] || { echo "SSL ERROR: the private key does not belong to the certificate"; rc=1; }

    if ! openssl x509 -in "$cert" -noout -checkend 0 >/dev/null 2>&1; then
        if [ "$allow_expired" = true ]; then
            echo "SSL WARNING: the certificate has EXPIRED ($(openssl x509 -in "$cert" -noout -enddate 2>/dev/null)); starting anyway because ssl_allow_expired is enabled. Browsers will warn or refuse until it is renewed."
        else
            echo "SSL ERROR: the certificate has expired (set ssl_allow_expired to start anyway, or renew it)"; rc=1
        fi
    elif ! openssl x509 -in "$cert" -noout -checkend 1209600 >/dev/null 2>&1; then
        echo "SSL WARNING: the certificate expires within 14 days"
    fi
    return $rc
}

# ssl_san_string <host[:port]>...: subjectAltName value for a certificate covering those addresses
# (IPv4 addresses become IP entries, names become DNS entries; localhost and 127.0.0.1 are always included).
ssl_san_string() {
    local h out="DNS:localhost,IP:127.0.0.1" seen=" localhost 127.0.0.1 "
    for h in "$@"; do
        h="${h%%:*}"                       # drop :port (IPv6 literals are not supported here)
        [ -n "$h" ] || continue
        case "$seen" in *" $h "*) continue ;; esac
        seen="$seen$h "
        if [[ "$h" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then out="$out,IP:$h"; else out="$out,DNS:$h"; fi
    done
    printf '%s' "$out"
}

# ssl_selfsigned_ensure <cert> <key> <san-string>: create (or renew) a self-signed certificate.
# It is regenerated when missing, when the address list changed, or when it expires within 30 days.
ssl_selfsigned_ensure() {
    local cert="$1" key="$2" san="$3" stamp
    stamp="$(dirname "$cert")/.san"
    if [ -r "$cert" ] && [ -r "$key" ] && [ "$(cat "$stamp" 2>/dev/null)" = "$san" ] \
       && openssl x509 -in "$cert" -noout -checkend 2592000 >/dev/null 2>&1; then
        return 0
    fi
    mkdir -p "$(dirname "$cert")" || return 1
    local cn="${san#*DNS:localhost,IP:127.0.0.1}"; cn="${cn#,}"; cn="${cn%%,*}"; cn="${cn#*:}"; cn="${cn:-localhost}"
    openssl req -x509 -newkey rsa:2048 -nodes -days 730 -keyout "$key" -out "$cert" \
        -subj "/CN=$cn/O=Nextcloud Home Assistant add-on" \
        -addext "subjectAltName=$san" -addext "basicConstraints=critical,CA:FALSE" \
        -addext "keyUsage=critical,digitalSignature,keyEncipherment" -addext "extendedKeyUsage=serverAuth" \
        >/dev/null 2>&1 || return 1
    chmod 600 "$key"; chmod 644 "$cert"
    printf '%s' "$san" >"$stamp"
}

# web_write_ui_conf <true|false> <cert> <key>: writes the Apache config for container port 443.
web_write_ui_conf() {
    local ssl="$1" cert="$2" key="$3"
    if [ "$ssl" = true ]; then
        a2enmod ssl >/dev/null 2>&1 || return 1
        cat >"$NC_APACHE_UI_CONF" <<EOF
# generated by nc-run (ssl: true). Listen 443 comes from the stock ports.conf once mod_ssl is loaded.
<VirtualHost *:443>
    ServerAdmin webmaster@localhost
    DocumentRoot ${NC_WEBROOT:-/data/nextcloud/html}
    ErrorLog \${APACHE_LOG_DIR}/error.log
    CustomLog \${APACHE_LOG_DIR}/access.log combined
    SSLEngine on
    SSLCertificateFile "$cert"
    SSLCertificateKeyFile "$key"
    SSLProtocol -all +TLSv1.2 +TLSv1.3
</VirtualHost>
EOF
    else
        # mod_ssl stays enabled in the container after a run with ssl: true (a restart keeps the filesystem). With it
        # loaded the stock ports.conf already listens on 443, and a second "Listen 443" makes Apache refuse to start.
        a2dismod -f ssl >/dev/null 2>&1 || true
        cat >"$NC_APACHE_UI_CONF" <<EOF
# generated by nc-run (ssl: false). Plain HTTP on the published web interface port.
Listen 443
<VirtualHost *:443>
    ServerAdmin webmaster@localhost
    DocumentRoot ${NC_WEBROOT:-/data/nextcloud/html}
    ErrorLog \${APACHE_LOG_DIR}/error.log
    CustomLog \${APACHE_LOG_DIR}/access.log combined
</VirtualHost>
EOF
    fi
}
